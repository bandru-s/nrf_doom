  wb[0] = '0' + (_g_bmapwidth / 100) % 10;
  wb[1] = '0' + (_g_bmapwidth / 10) % 10;
  wb[2] = '0' + _g_bmapwidth % 10;
  wb[3] = 0;
////  semihost_write0(wb);

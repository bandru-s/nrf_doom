  char hb[8];
  hb[0] = '0' + (_g_bmapheight / 100) % 10;
  hb[1] = '0' + (_g_bmapheight / 10) % 10;
  hb[2] = '0' + _g_bmapheight % 10;
  hb[3] = 0;
////  semihost_write0(hb);
////  semihost_write0(" alloc=");
  char ab[10];
  ab[0] = '0' + (alloc_size / 1000000) % 10;
  ab[1] = '0' + (alloc_size / 100000) % 10;
  ab[2] = '0' + (alloc_size / 10000) % 10;
  ab[3] = '0' + (alloc_size / 1000) % 10;
  ab[4] = '0' + (alloc_size / 100) % 10;
  ab[5] = '0' + (alloc_size / 10) % 10;
  ab[6] = '0' + alloc_size % 10;
  ab[7] = '\n';
  ab[8] = 0;
